        (".io Games", "Agario Style"),
        ("Action Games", "Action"),
        ("Puzzle Games", "Puzzle"),
        ("Shooting Games", "Shooter"),
        ("Sports Games", "Sports"),
        ("Racing Games", "Racing"),
