def esc(s):
    return html.escape(str(s), quote=True)


def load_games():
    with open(DATA_FILE, encoding="utf-8") as f:
        games = json.load(f)
    for i, g in enumerate(games):
        g["_i"] = i
        g.setdefault("categories", [])
        g.setdefault("rating", None)
    return games


def play_url(g):
    return "./play?g=" + g["slug"]


