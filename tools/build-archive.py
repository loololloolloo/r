# Cache-busting token for the local stylesheet/scripts. It is derived from the
# asset contents in main(), not hand-maintained: the old fixed "v=28" let a
# rebuilt cg.css sit behind a 4h max-age while the HTML (10min) updated, so
# returning visitors rendered the new markup with stale styles.
VERSION = "0"
BUILD_STAMP = datetime.datetime.now(datetime.timezone.utc).strftime("%Y-%m-%d %H:%M:%SZ")
MARKER = ("<!-- Generated by tools/build-archive.py - edit that script, not this file. -->\n"
          f"<!-- build {BUILD_STAMP} -->")


def asset_version(games_js):
    """sha1 of everything the pages link, so any change busts the cache."""
    h = hashlib.sha1()
    h.update(games_js.encode("utf-8"))
    for rel in ("assets/css/cg.css", "assets/js/cg-site.js", "assets/cg2026/theme.css"):
        try:
            with open(os.path.join(ROOT, rel), "rb") as fh:
                h.update(fh.read())
        except OSError:
            pass
    return h.hexdigest()[:10]

